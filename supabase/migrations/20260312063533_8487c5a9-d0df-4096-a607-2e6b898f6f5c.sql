
-- Pincode serviceability table
CREATE TABLE public.serviceable_pincodes (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  pincode TEXT NOT NULL,
  city TEXT,
  state TEXT,
  cod_available BOOLEAN DEFAULT true,
  estimated_days INTEGER DEFAULT 5,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  UNIQUE(pincode)
);

ALTER TABLE public.serviceable_pincodes ENABLE ROW LEVEL SECURITY;

-- Public read
CREATE POLICY "Pincodes are public read"
ON public.serviceable_pincodes
FOR SELECT
TO public
USING (true);

-- Admin manage
CREATE POLICY "Admins manage pincodes"
ON public.serviceable_pincodes
FOR ALL
TO authenticated
USING (has_role(auth.uid(), 'admin'::app_role))
WITH CHECK (has_role(auth.uid(), 'admin'::app_role));

